param(
    [string]$DesignDirectory = 'F:/Codex-Project/MCFPV/deliverables/drone-design-20261010/blockbench',
    [string]$ProjectDirectory = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
$sourcePath = Join-Path $DesignDirectory 'fpv_dronecraft_v1.bbmodel'
$texturePath = Join-Path $DesignDirectory 'fpv_dronecraft_v1.png'
$model = Get-Content -Raw -LiteralPath $sourcePath | ConvertFrom-Json
if ($model.meta.model_format -ne 'modded_entity' -or !$model.meta.box_uv -or !$model.modded_entity_flip_y) {
    throw 'Expected an exported Java entity model with box UV and flipped Y.'
}
if ($model.elements.Count -ne 280 -or $model.groups.Count -ne 23) { throw 'Unexpected drone design revision.' }
$sourceSha = (Get-FileHash -LiteralPath $sourcePath -Algorithm SHA256).Hash.ToLowerInvariant()
$textureSha = (Get-FileHash -LiteralPath $texturePath -Algorithm SHA256).Hash.ToLowerInvariant()
$groups = @{}
$cubes = @{}
$groupNodes = @{}
foreach ($group in $model.groups) { $groups[$group.uuid] = $group }
foreach ($cube in $model.elements) {
    if ($cube.type -ne 'cube' -or !$cube.box_uv -or !$cube.export -or !$cube.visibility -or $cube.mirror_uv) {
        throw "Unsupported element: $($cube.name)"
    }
    foreach ($value in @($cube.from) + @($cube.to) + @($cube.origin) + @($cube.rotation) + @($cube.uv_offset) + @($cube.inflate)) {
        if ([double]::IsNaN($value) -or [double]::IsInfinity($value)) { throw "Nonfinite element: $($cube.name)" }
    }
    $cubes[$cube.uuid] = $cube
}
function Index-Nodes($node) {
    if ($node -is [string]) { return }
    $groupNodes[$node.uuid] = $node
    foreach ($child in $node.children) { Index-Nodes $child }
}
foreach ($node in $model.outliner) { Index-Nodes $node }

$lines = [System.Collections.Generic.List[string]]::new()
function Add-Line([string]$line = '') { $lines.Add($line) }
function F([double]$number) {
    if ([Math]::Abs($number) -lt 1.0e-12) { $number = 0.0 }
    $value = $number.ToString('0.############', [System.Globalization.CultureInfo]::InvariantCulture)
    if (!$value.Contains('.')) { $value += '.0' }
    return $value + 'f'
}
function Relative-Pose($origin, $parentOrigin, $rotation) {
    $values = @((F (-($origin[0] - $parentOrigin[0]))), (F (-($origin[1] - $parentOrigin[1]))), (F ($origin[2] - $parentOrigin[2])), (F (-$rotation[0] * [Math]::PI / 180.0)), (F (-$rotation[1] * [Math]::PI / 180.0)), (F ($rotation[2] * [Math]::PI / 180.0)))
    return 'PartPose.offsetAndRotation(' + ($values -join ', ') + ')'
}
function Emit-Cube($cube, [string]$parentVariable, $parentOrigin) {
    $variable = 'cube' + $script:variableIndex++
    $pose = Relative-Pose $cube.origin $parentOrigin $cube.rotation
    $box = @((F ($cube.origin[0] - $cube.to[0])), (F ($cube.origin[1] - $cube.to[1])), (F ($cube.from[2] - $cube.origin[2])), (F ($cube.to[0] - $cube.from[0])), (F ($cube.to[1] - $cube.from[1])), (F ($cube.to[2] - $cube.from[2]))) -join ', '
    Add-Line "`t`t$parentVariable.addOrReplaceChild(`"$($cube.name)`","
    Add-Line "`t`t`t`tCubeListBuilder.create().texOffs($([int]$cube.uv_offset[0]), $([int]$cube.uv_offset[1]))"
    Add-Line "`t`t`t`t`t`t.addBox($box, new CubeDeformation($(F $cube.inflate))), $pose);"
}
function Emit-Group($group, [string]$parentVariable, $parentOrigin, [string]$overrideName = '') {
    $variable = 'part' + $script:variableIndex++
    $partName = if ($overrideName) { $overrideName } else { $group.name }
    $pose = Relative-Pose $group.origin $parentOrigin $group.rotation
    Add-Line "`t`tPartDefinition $variable = $parentVariable.addOrReplaceChild(`"$partName`", CubeListBuilder.create(), $pose);"
    foreach ($child in $groupNodes[$group.uuid].children) {
        if ($child -is [string]) { Emit-Cube $cubes[$child] $variable $group.origin }
        else { Emit-Group $groups[$child.uuid] $variable $group.origin }
    }
    return $variable
}

Add-Line 'package com.tenicana.dronecraft.client.render;'
Add-Line
Add-Line 'import net.minecraft.client.model.geom.PartPose;'
Add-Line 'import net.minecraft.client.model.geom.builders.CubeDeformation;'
Add-Line 'import net.minecraft.client.model.geom.builders.CubeListBuilder;'
Add-Line 'import net.minecraft.client.model.geom.builders.PartDefinition;'
Add-Line
Add-Line '/** Generated by tools/import-drone-design.ps1; geometry and box UV are the supplied Blockbench design. */'
Add-Line 'final class ImportedDroneDesign {'
Add-Line "`tstatic final String SOURCE_SHA256 = `"$sourceSha`";"
Add-Line "`tstatic final String TEXTURE_SHA256 = `"$textureSha`";"
Add-Line "`tstatic final int SOURCE_CUBE_COUNT = $($model.elements.Count);"
Add-Line "`tstatic final int SOURCE_GROUP_COUNT = $($model.groups.Count);"
Add-Line "`tstatic final int TEXTURE_WIDTH = $($model.resolution.width);"
Add-Line "`tstatic final int TEXTURE_HEIGHT = $($model.resolution.height);"
Add-Line '`tstatic final float ARM_ORIGIN_Y = -2.6f;'
Add-Line '`tstatic final float ROTOR_ORIGIN_Y = -4.9f;'
Add-Line '`tstatic final float ARM_RADIUS = (float) Math.sqrt(12.0 * 12.0 * 2.0);'
Add-Line '`tstatic final float[] ARM_X = {12.0f, -12.0f, 12.0f, -12.0f};'
Add-Line '`tstatic final float[] ARM_Z = {-12.0f, -12.0f, 12.0f, 12.0f};'
Add-Line
Add-Line '`tprivate ImportedDroneDesign() {}'
Add-Line
Add-Line '`tstatic void addTo(PartDefinition parent) {'
Add-Line '`t`tPartDefinition design = parent.addOrReplaceChild("design", CubeListBuilder.create(),'
Add-Line '`t`t`t`tPartPose.offsetAndRotation(0.0f, 4.0f, 0.0f, 0.0f, (float) Math.PI, 0.0f));'
Add-Line '`t`taddFixedParts(design);'
Add-Line '`t`tfor (int index = 0; index < 8; index++) {'
Add-Line '`t`t`tswitch (index & 3) {'
for ($index = 0; $index -lt 4; $index++) { Add-Line "`t`t`t`tcase $index -> { addAssembly$index(design, index); addRotor$index(design, index); }" }
Add-Line '`t`t`t}'
Add-Line '`t`t}'
Add-Line '`t}'
Add-Line
Add-Line '`tprivate static void addFixedParts(PartDefinition design) {'
$script:variableIndex = 0
foreach ($name in @('chassis','battery','fpv_camera','rear_antenna')) {
    $group = $model.groups | Where-Object name -eq $name
    $null = Emit-Group $group 'design' @(0,0,0)
}
Add-Line '`t}'
for ($index = 0; $index -lt 4; $index++) {
    Add-Line
    Add-Line "`tprivate static void addAssembly$index(PartDefinition design, int index) {"
    $script:variableIndex = 0
    $group = $model.groups | Where-Object name -like "arm_$($index)_*"
    $pose = Relative-Pose $group.origin @(0,0,0) $group.rotation
    Add-Line "`t`tPartDefinition assembly = design.addOrReplaceChild(`"assembly_`" + index, CubeListBuilder.create(), $pose);"
    foreach ($child in $groupNodes[$group.uuid].children) {
        if ($child -is [string]) { Emit-Cube $cubes[$child] 'assembly' $group.origin }
        else { $null = Emit-Group $groups[$child.uuid] 'assembly' $group.origin }
    }
    Add-Line '`t}'
    Add-Line
    Add-Line "`tprivate static void addRotor$index(PartDefinition design, int index) {"
    $script:variableIndex = 0
    $group = $model.groups | Where-Object name -eq "rotor_$index"
    $pose = Relative-Pose $group.origin @(0,0,0) $group.rotation
    Add-Line "`t`tPartDefinition rotor = design.addOrReplaceChild(`"rotor_`" + index, CubeListBuilder.create(), $pose);"
    foreach ($child in $groupNodes[$group.uuid].children) { Emit-Cube $cubes[$child] 'rotor' $group.origin }
    Add-Line '`t}'
}
Add-Line '}'

$outputPath = Join-Path $ProjectDirectory 'fabric-mod/src/client/java/com/tenicana/dronecraft/client/render/ImportedDroneDesign.java'
