[System.IO.File]::WriteAllText($outputPath, ($lines -join "`n").Replace('`t', "`t") + "`n", $utf8)
$fixture = [ordered]@{ source_sha256 = $sourceSha; texture_sha256 = $textureSha; resolution = $model.resolution; groups = $model.groups; outliner = $model.outliner; elements = $model.elements }
[System.IO.File]::WriteAllText($fixturePath, ($fixture | ConvertTo-Json -Depth 30) + "`n", $utf8)
Copy-Item -LiteralPath $texturePath -Destination $textureOutput -Force
Write-Output "Imported $($model.elements.Count) cubes, $($model.groups.Count) groups, and the unchanged texture. Source SHA256: $sourceSha"
